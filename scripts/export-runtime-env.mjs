#!/usr/bin/env node

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

function argValue(name, fallback = "") {
  const index = process.argv.indexOf(name);
  if (index === -1) return fallback;
  return process.argv[index + 1] || fallback;
}

function readDeployment(path) {
  if (!existsSync(path)) {
    throw new Error(`missing_deployment:${path}`);
  }

  return JSON.parse(readFileSync(path, "utf8"));
}

function envLine(key, value) {
  return `${key}=${value ?? ""}`;
}

function runtimeEnv(deployment, deploymentPath) {
  const rpcKey = deployment.network === "base" ? "BASE_RPC_URL" : "BASE_SEPOLIA_RPC_URL";
  const rpcDefault = deployment.network === "base" ? "https://mainnet.base.org" : "https://sepolia.base.org";

  return [
    "# Generated by npm run export:env",
    envLine("SPENDOS_DEPLOYMENT_FILE", deploymentPath),
    envLine("SPENDOS_NETWORK", deployment.network || ""),
    envLine("SPENDOS_CHAIN_ID", deployment.chainId || ""),
    envLine("SPENDOS_VAULT_ADDRESS", deployment.vaultAddress || ""),
    envLine("USDC_ADDRESS", deployment.usdcAddress || ""),
    envLine(rpcKey, process.env[rpcKey] || rpcDefault),
    envLine("SPENDOS_OPERATOR_PRIVATE_KEY", "0x..."),
    envLine("SPENDOS_AGENT_VAULT", "0x..."),
    "",
  ].join("\n");
}

function main() {
  const deploymentPath = argValue("--deployment", process.env.SPENDOS_DEPLOYMENT_FILE || "");
  if (!deploymentPath) {
    throw new Error("missing_deployment_arg");
  }

  const deployment = readDeployment(deploymentPath);
  const output = argValue("--out", join("deployments", `${basename(deploymentPath, ".json")}.env`));
  const content = runtimeEnv(deployment, deploymentPath);
  writeFileSync(output, content);

  console.log(
    JSON.stringify(
      {
        status: "exported",
        deployment: deploymentPath,
        output,
        vaultAddress: deployment.vaultAddress,
        usdcAddress: deployment.usdcAddress,
        network: deployment.network,
        chainId: deployment.chainId,
      },
      null,
      2,
    ),
  );
}

main();
